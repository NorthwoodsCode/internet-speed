#!/usr/bin/env python3
"""Generate a one-page monthly performance PDF for emailing your ISP.

The report covers a single calendar month (in local time) and includes:
  - Header with ISP plan info (from SPECTRUM_PROMISED_* env vars)
  - Summary stats table (samples, % below promised, outage count)
  - Download/upload/ping time series with promised baseline and
    outage shading
  - Mean download by hour-of-day bar chart
  - Outage list (start, end, sample count, worst metrics)

Designed to be attached to a complaint email. One page, default A4,
matplotlib's PDF backend so no new dependencies beyond what plot.py
already needs.
"""

from __future__ import annotations

import argparse
import calendar
import datetime as dt
import sys
from pathlib import Path

# plot.py doubles as the shared library: CSV loading, timestamp handling,
# outage detection, hour bucketing and the matplotlib panel renderers all
# live there so the PNG chart and this PDF can't drift apart.
sys.path.insert(0, str(Path(__file__).resolve().parent))
from plot import (  # noqa: E402
    OUTAGE_DOWN_BELOW,
    OUTAGE_PING_ABOVE,
    PROG,
    detect_outages,
    find_csvs,
    hour_means,
    import_matplotlib,
    load_rows,
    outage_spans,
    pct_below,
    plot_hours,
    plot_metric,
    promised_from_env,
)


def parse_args() -> argparse.Namespace:
    p = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    p.add_argument(
        "--month",
        help="Month to report on as YYYY-MM (default: last complete month)",
    )
    p.add_argument(
        "--csv",
        type=Path,
        help="CSV file (default: all speed-*.csv in SPEED_LOG_DIR)",
    )
    p.add_argument(
        "--output",
        "-o",
        type=Path,
        help="Output PDF path (default: report-YYYY-MM.pdf)",
    )
    return p.parse_args()


def parse_month(spec: str | None) -> tuple[dt.datetime, dt.datetime, str]:
    """Return (start, end_exclusive, 'YYYY-MM') for the chosen month, local time."""
    if spec:
        try:
            year, month = (int(x) for x in spec.split("-"))
            start = dt.datetime(year, month, 1)  # also rejects month 0 or 13
        except ValueError:
            sys.exit(f"{PROG}: bad --month '{spec}' (expected YYYY-MM)")
    else:
        first_of_this_month = dt.date.today().replace(day=1)
        prev_last = first_of_this_month - dt.timedelta(days=1)
        start = dt.datetime(prev_last.year, prev_last.month, 1)
    year, month = start.year, start.month
    end = dt.datetime(year + (month // 12), (month % 12) + 1, 1)
    return start, end, f"{year:04d}-{month:02d}"


def filter_month(times, pings, downs, ups, start, end):
    idx = [i for i, t in enumerate(times) if start <= t < end]
    return ([times[i] for i in idx], [pings[i] for i in idx],
            [downs[i] for i in idx], [ups[i] for i in idx])


def main() -> int:
    args = parse_args()
    paths = find_csvs(args.csv)
    times, pings, downs, ups = load_rows(paths)
    if not times:
        sys.exit(f"{PROG}: no data rows found")

    start, end, label = parse_month(args.month)
    times, pings, downs, ups = filter_month(times, pings, downs, ups, start, end)
    if not times:
        sys.exit(f"{PROG}: no samples in {label} (range available: see speedtest.sh summary)")

    output = args.output or Path(f"report-{label}.pdf")
    promised_down, promised_up = promised_from_env()
    outages = detect_outages(times, pings, downs)
    spans = outage_spans(times, outages)

    plt, mdates = import_matplotlib()
    # A4 portrait at 100 dpi is roughly 8.27 x 11.69 inches.
    fig = plt.figure(figsize=(8.27, 11.69))
    gs = fig.add_gridspec(
        6, 1, height_ratios=[0.4, 0.6, 1.0, 1.0, 1.0, 1.2],
        hspace=0.55, left=0.07, right=0.96, top=0.96, bottom=0.05,
    )

    # 1. Header
    ax_header = fig.add_subplot(gs[0]); ax_header.axis("off")
    ax_header.text(0, 0.7, "Internet Performance Report", fontsize=18, fontweight="bold")
    ax_header.text(0, 0.3,
                   f"{calendar.month_name[start.month]} {start.year}  ·  "
                   f"generated by internet-speed  ·  "
                   f"https://github.com/NorthwoodsCode/internet-speed",
                   fontsize=9, color="gray")

    # 2. Stats table
    ax_stats = fig.add_subplot(gs[1]); ax_stats.axis("off")
    _render_stats(ax_stats, times, pings, downs, ups, promised_down, promised_up, outages)

    # 3-5. Time series
    ax_down = fig.add_subplot(gs[2])
    ax_up = fig.add_subplot(gs[3], sharex=ax_down)
    ax_ping = fig.add_subplot(gs[4], sharex=ax_down)
    plot_metric(ax_down, times, downs, "Download (Mbps)", "tab:blue", promised_down, spans, compact=True)
    plot_metric(ax_up, times, ups, "Upload (Mbps)", "tab:green", promised_up, spans, compact=True)
    plot_metric(ax_ping, times, pings, "Ping (ms)", "tab:orange", None, spans, compact=True)
    for ax in (ax_down, ax_up):
        plt.setp(ax.get_xticklabels(), visible=False)
    ax_ping.xaxis.set_major_formatter(mdates.DateFormatter("%m-%d"))

    # 6. Hour-of-day + outage list
    gs_bottom = gs[5].subgridspec(1, 2, width_ratios=[1.2, 1])
    ax_hours = fig.add_subplot(gs_bottom[0])
    ax_outages = fig.add_subplot(gs_bottom[1]); ax_outages.axis("off")
    plot_hours(ax_hours, hour_means(times, downs), promised_down, compact=True)
    _render_outage_list(ax_outages, outages, times)

    fig.savefig(output, format="pdf")
    print(f"wrote {output} ({len(times)} samples, {len(outages)} outage(s))")
    return 0


def _render_stats(ax, times, pings, downs, ups, promised_down, promised_up, outages):
    def avg(xs): return sum(xs) / len(xs) if xs else 0
    rows = [
        ("Samples", f"{len(times)}"),
        ("Date range", f"{times[0]:%Y-%m-%d %H:%M} → {times[-1]:%Y-%m-%d %H:%M}"),
        ("Mean download", f"{avg(downs):.1f} Mbps"),
        ("Mean upload",   f"{avg(ups):.1f} Mbps"),
        ("Mean ping",     f"{avg(pings):.1f} ms"),
    ]
    if promised_down:
        rows.append(("Promised download",
                     f"{promised_down:g} Mbps  ({pct_below(downs, promised_down):.1f}% of samples below)"))
    if promised_up:
        rows.append(("Promised upload",
                     f"{promised_up:g} Mbps  ({pct_below(ups, promised_up):.1f}% of samples below)"))
    rows.append(("Outage events",
                 f"{len(outages)}  (down < {OUTAGE_DOWN_BELOW:g} Mbps or ping > {OUTAGE_PING_ABOVE:g} ms)"))
    for i, (k, v) in enumerate(rows):
        y = 1 - (i + 0.7) / (len(rows) + 0.5)
        ax.text(0.00, y, k, fontsize=9, fontweight="bold")
        ax.text(0.32, y, v, fontsize=9, family="monospace")


def _render_outage_list(ax, outages, times):
    ax.text(0, 1.0, "Outage events", fontsize=10, fontweight="bold")
    if not outages:
        ax.text(0, 0.85, "(none in this period)", fontsize=9, color="gray")
        return
    shown = outages[:8]
    for i, (s, e) in enumerate(shown):
        y = 0.85 - i * 0.10
        line = f"{times[s]:%m-%d %H:%M} → {times[e]:%m-%d %H:%M}  ({e - s + 1} samples)"
        ax.text(0, y, line, fontsize=8, family="monospace")
    if len(outages) > 8:
        ax.text(0, 0.85 - len(shown) * 0.10,
                f"…and {len(outages) - 8} more", fontsize=8, color="gray")


if __name__ == "__main__":
    sys.exit(main())
